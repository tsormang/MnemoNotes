import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const folder = 'pharmacy-roles'
const sortBase = 2100
const dir = path.join(root, 'public/icons', folder)

function labelFromSlug(slug) {
  return slug
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

/** @type {Array<{ id: string; label: string; path: string; sortOrder: number }>} */
const entries = []

const files = fs
  .readdirSync(dir)
  .filter((name) => name.endsWith('.png'))
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }))

files.forEach((file, index) => {
  const slug = file.replace(/\.png$/i, '')
  entries.push({
    id: `role-${slug}`,
    label: labelFromSlug(slug),
    path: `/icons/${folder}/${file}`,
    sortOrder: sortBase + index + 1,
  })
})

const defaultIconId = entries.find((entry) => entry.id === 'role-manager')?.id ?? entries[0]?.id ?? 'role-manager'

const tsPath = path.join(root, 'src/lib/icons/role-icons.generated.ts')
const tsBody = `/** Generated by scripts/generate-role-icon-catalog.mjs — do not edit manually. */
import type { AppIcon } from './types'

export const ROLE_ICONS: AppIcon[] = [
${entries
  .map(
    (entry) =>
      `  { id: '${entry.id}', label: '${entry.label.replace(/'/g, "''")}', path: '${entry.path}', entityTypes: ['company_role'], tags: ['pharmacy'], sortOrder: ${entry.sortOrder} },`,
  )
  .join('\n')}
]

export const DEFAULT_ROLE_ICON_ID = '${defaultIconId}' as const
`

fs.writeFileSync(tsPath, tsBody)

console.log(`Generated ${entries.length} role icons`)
console.log(`  TS: ${tsPath}`)
console.log(`  Default: ${defaultIconId}`)
