import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()

const collections = [
  {
    key: 'finance',
    folder: 'flat-finance-icons',
    sortBase: 3000,
    labelPrefix: 'Finance',
  },
  {
    key: 'medical',
    folder: 'medical-health',
    sortBase: 4000,
    labelPrefix: 'Medical',
  },
]

function slugFromFile(file) {
  return file.replace(/-icon\.png$/i, '')
}

function labelFromSlug(slug) {
  return slug
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

/** @type {Array<{ id: string; label: string; path: string; collection: string; sortOrder: number }>} */
const entries = []

for (const collection of collections) {
  const dir = path.join(root, 'public/icons', collection.folder)
  const files = fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.png'))
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }))

  files.forEach((file, index) => {
    const slug = slugFromFile(file)
    entries.push({
      id: `note-${collection.key}-${slug}`,
      label: labelFromSlug(slug),
      path: `/icons/${collection.folder}/${file}`,
      collection: collection.key,
      sortOrder: collection.sortBase + index + 1,
    })
  })
}

const firstFinance = entries.find((entry) => entry.collection === 'finance')
const firstMedical = entries.find((entry) => entry.collection === 'medical')

const tsPath = path.join(root, 'src/lib/icons/note-icons.generated.ts')
const tsBody = `/** Generated by scripts/generate-note-icon-catalog.mjs — do not edit manually. */
import type { AppIcon } from './types'

export const NOTE_ICONS: AppIcon[] = [
${entries
  .map(
    (entry) =>
      `  { id: '${entry.id}', label: '${entry.label.replace(/'/g, "''")}', path: '${entry.path}', entityTypes: ['note'], tags: ['${entry.collection}'], sortOrder: ${entry.sortOrder}, noteIconCollection: '${entry.collection}' },`,
  )
  .join('\n')}
]

export const DEFAULT_NOTE_ICON_BY_COLLECTION = {
  finance: '${firstFinance?.id ?? 'note-finance-bank'}',
  medical: '${firstMedical?.id ?? 'note-medical-capsule'}',
} as const
`

fs.writeFileSync(tsPath, tsBody)

console.log(`Generated ${entries.length} note icons`)
console.log(`  TS: ${tsPath}`)
