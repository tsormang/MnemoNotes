import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const avatarsRoot = path.join(root, 'public/avatars')
const genders = ['male', 'female']

/** @type {Array<{ id: string; label: string; path: string; gender: string; sortOrder: number; file: string }>} */
const entries = []

for (const gender of genders) {
  const dir = path.join(avatarsRoot, gender)
  const files = fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.png'))
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }))

  for (const file of files) {
    const match = file.match(/^avatar_(\d+)\.png$/)
    if (!match) continue

    const number = match[1]
    const id = `avatar-${gender}-${number}`
    entries.push({
      id,
      label: `${gender === 'male' ? 'Male' : 'Female'} avatar ${Number(number)}`,
      path: `/avatars/${gender}/${file}`,
      gender,
      sortOrder: (gender === 'male' ? 1000 : 2000) + Number(number),
      file,
    })
  }
}

const tsPath = path.join(root, 'src/lib/icons/personnel-avatars.generated.ts')
const tsBody = `/** Generated by scripts/generate-avatar-catalog.mjs — do not edit manually. */
import type { AppIcon } from './types'

export const PERSONNEL_AVATAR_ICONS: AppIcon[] = [
${entries
  .map(
    (entry) =>
      `  { id: '${entry.id}', label: '${entry.label}', path: '${entry.path}', entityTypes: ['personnel'], tags: ['${entry.gender}'], sortOrder: ${entry.sortOrder}, avatarGender: '${entry.gender}' },`,
  )
  .join('\n')}
]

export const DEFAULT_PERSONNEL_AVATAR_BY_GENDER = {
  male: '${entries.find((entry) => entry.gender === 'male')?.id ?? 'avatar-male-001'}',
  female: '${entries.find((entry) => entry.gender === 'female')?.id ?? 'avatar-female-002'}',
} as const
`
fs.writeFileSync(tsPath, tsBody)

const sqlPath = path.join(root, 'supabase/migrations/20260828160000_personnel_avatars.sql')
const legacyPersonIconIds = [
  'person-default',
  ...Array.from({ length: 11 }, (_, index) => `person-${String(index + 1).padStart(2, '0')}`),
]

const sqlBody = `-- Personnel avatars (male/female) + avatar_gender on people entities.

create type public.avatar_gender as enum ('male', 'female');

alter table public.app_icons
  add column avatar_gender public.avatar_gender;

alter table public.personnel
  add column avatar_gender public.avatar_gender not null default 'female';

insert into public.app_icons (id, label, path, entity_types, tags, sort_order, avatar_gender) values
${entries
  .map(
    (entry) =>
      `  ('${entry.id}', '${entry.label.replace(/'/g, "''")}', '${entry.path}', array['personnel']::public.icon_entity_type[], '{${entry.gender}}', ${entry.sortOrder}, '${entry.gender}')`,
  )
  .join(',\n')};

update public.personnel
set
  icon_id = 'avatar-female-002',
  avatar_gender = 'female'
where icon_id in (${legacyPersonIconIds.map((id) => `'${id}'`).join(', ')});

alter table public.personnel
  alter column icon_id set default 'avatar-female-002';

delete from public.app_icons
where id in (${legacyPersonIconIds.map((id) => `'${id}'`).join(', ')});
`

fs.writeFileSync(sqlPath, sqlBody)

console.log(`Generated ${entries.length} personnel avatars`)
console.log(`  TS: ${tsPath}`)
console.log(`  SQL: ${sqlPath}`)
